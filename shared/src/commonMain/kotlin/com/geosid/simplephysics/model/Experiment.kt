    val badgeRes: StringResource,
    val teaserRes: StringResource,
    val magicPhenomenonRes: StringResource,
    val sciencePrincipleRes: StringResource,
    val formulaTitleRes: StringResource,
    val formula: String,
    val howToTryAtHomeRes: StringResource
